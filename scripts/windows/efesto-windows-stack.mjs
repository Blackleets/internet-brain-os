// One-click Windows stack for Efesto: Ollama (qwen3.5:2b) → Kernel :4310 (via the existing launcher)
// → dashboard :3311 (next start) → Hermes queue worker (supervised). Idempotent: anything already
// healthy is reused, never duplicated. Tokens are never printed; the Kernel creates and owns its token.
// The dashboard is a production build (next start) bound to 127.0.0.1 that reaches the Kernel through its own
// same-origin loopback bridge (EFESTO_LOCAL_KERNEL_TOKEN_FILE): no browser extension and no pairing code.
// Usage: node scripts/windows/efesto-windows-stack.mjs [plan|write-config|start|open|stop|status|supervise-worker]
import { spawn } from 'node:child_process';
import { existsSync } from 'node:fs';
import { mkdir, readFile, rm, writeFile, open } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { readLauncherConfig, writeLauncherConfig } from '../efesto-bootstrap.mjs';

export const KERNEL_PORT = 4310;
export const DASHBOARD_PORT = 3311;
export const OLLAMA_HOST = '127.0.0.1:11434';
export const MODEL = 'qwen3.5:2b';
const HERE = dirname(fileURLToPath(import.meta.url));
export const DEFAULT_REPO_ROOT = resolve(HERE, '..', '..');

const say = (m) => console.log(`[Efesto] ${m}`);

/** All locations the stack uses. Windows: %LOCALAPPDATA%\Efesto; elsewhere ~/.efesto (dev/CI only). */
export function windowsStackPaths(env = process.env, repoRoot = DEFAULT_REPO_ROOT) {
  const base = env.EFESTO_HOME
    ? resolve(env.EFESTO_HOME)
    : env.LOCALAPPDATA ? join(env.LOCALAPPDATA, 'Efesto') : join(env.HOME ?? env.USERPROFILE ?? '.', '.efesto');
  const dataDir = join(base, 'kernel-data');
  // Efesto-owned pinned Hermes (installed when the user's Hermes is not at the validated revision)
  // wins over the user's standard install; EFESTO_HERMES_ROOT is set by the installer.
  const ownHermes = join(base, 'hermes-agent');
  const hermesRoot = env.EFESTO_HERMES_ROOT
    ? resolve(env.EFESTO_HERMES_ROOT)
    : existsSync(ownHermes) || !env.LOCALAPPDATA ? ownHermes : join(env.LOCALAPPDATA, 'hermes', 'hermes-agent');
  const win = (env.EFESTO_PLATFORM ?? process.platform) === 'win32';
  return {
    repoRoot,
    base,
    dataDir,
    tokenFile: join(dataDir, 'kernel-api-token'),
    obsidianDir: join(base, 'obsidian'),
    logsDir: join(base, 'logs'),
    stateFile: join(base, 'stack-processes.json'),
    workerEnvFile: join(base, 'hermes-worker.env'),
    pauseFile: join(base, 'hermes-worker.pause'),
    runsFile: join(base, 'logs', 'hermes-worker-runs.jsonl'),
    hermesRoot,
    hermesExecutable: win ? join(hermesRoot, 'venv', 'Scripts', 'hermes.exe') : join(hermesRoot, 'venv', 'bin', 'hermes'),
  };
}

/** Same keys and values as scripts/live-box/hermes-worker-env.example, with Windows paths. No secrets. */
export function workerEnvEntries(paths) {
  return [
    ['OLLAMA_HOST', OLLAMA_HOST],
    ['OLLAMA_CONTEXT_LENGTH', '8192'],
    ['HERMES_INFERENCE_PROVIDER', 'custom'],
    ['HERMES_INFERENCE_MODEL', MODEL],
    ['CUSTOM_BASE_URL', `http://${OLLAMA_HOST}/v1`],
    ['HEPHAESTUS_HERMES_EXECUTABLE', paths.hermesExecutable],
    ['HEPHAESTUS_HERMES_ONESHOT_TIMEOUT_MS', '240000'],
    ['HEPHAESTUS_HERMES_WORKER_TIMEOUT_MS', '300000'],
    ['HEPHAESTUS_HERMES_MAX_TURNS', '4'],
    ['HEPHAESTUS_SELECTION_BACKEND', 'ollama-structured'],
    ['EFESTO_REPO_ROOT', paths.repoRoot],
    ['EFESTO_KERNEL_URL', `http://127.0.0.1:${KERNEL_PORT}`],
    ['EFESTO_KERNEL_TOKEN_FILE', paths.tokenFile],
    ['EFESTO_WORKER_PAUSE_FILE', paths.pauseFile],
    ['EFESTO_WORKER_RUNS_FILE', paths.runsFile],
  ];
}

export function renderWorkerEnv(paths) {
  return ['# Efesto Hermes worker environment (generated by efesto-windows-stack.mjs). No secrets here.',
    ...workerEnvEntries(paths).map(([k, v]) => `${k}=${v}`), ''].join('\n');
}

export function parseEnvFile(text) {
  const out = {};
  for (const line of String(text).split(/\r?\n/)) {
    const m = /^([A-Z][A-Z0-9_]*)=(.*)$/.exec(line.trim());
    if (m) out[m[1]] = m[2];
  }
  return out;
}

/** Env for the Kernel: fixed port 4310, private data dir under %LOCALAPPDATA%. */
export function kernelEnv(paths, env = process.env) {
  // Extension pairing is optional in the installed product: the Kernel never shows a pairing code
  // and the launcher never restarts it to issue one (EFESTO_PAIRING_OPTIONAL, efesto-launcher-core.mjs).
  return { ...env, HEPHAESTUS_PORT: String(KERNEL_PORT), HEPHAESTUS_DATA_DIR: paths.dataDir, HEPHAESTUS_OBSIDIAN_DIR: paths.obsidianDir, HEPHAESTUS_HERMES_EXECUTABLE: paths.hermesExecutable, HEPHAESTUS_PAIRING: '0', EFESTO_PAIRING_OPTIONAL: '1' };
}

export const DASHBOARD_URL = `http://127.0.0.1:${DASHBOARD_PORT}/`;

/** Env for `next start`: production, loopback-only bridge to the Kernel. Only the token *path* is passed. */
export function dashboardEnv(paths, env = process.env) {
  return { ...env, NODE_ENV: 'production', NEXT_TELEMETRY_DISABLED: '1', EFESTO_LOCAL_KERNEL_TOKEN_FILE: paths.tokenFile, EFESTO_LOCAL_KERNEL_URL: `http://127.0.0.1:${KERNEL_PORT}` };
}

/** How the default browser is opened on Windows (no console window). */
export function browserOpenCommand(url = DASHBOARD_URL) {
  return { command: 'rundll32.exe', args: ['url.dll,FileProtocolHandler', url] };
}

/** The ordered steps `start` performs; `plan` prints these without touching anything. */
export function stackPlan(paths) {
  return [
    { id: 'config', label: 'Preparar la configuración local', detail: paths.workerEnvFile },
    { id: 'ollama', label: `Arrancar Ollama y comprobar el modelo ${MODEL}`, detail: `http://${OLLAMA_HOST}` },
    { id: 'kernel', label: `Arrancar el Kernel de Efesto en el puerto ${KERNEL_PORT}`, detail: paths.dataDir },
    { id: 'dashboard', label: `Arrancar el panel en http://127.0.0.1:${DASHBOARD_PORT}`, detail: join(paths.repoRoot, 'apps', 'dashboard') },
    { id: 'worker', label: 'Arrancar el trabajador de Hermes', detail: paths.hermesExecutable },
  ];
}

async function readJson(file) { try { return JSON.parse(await readFile(file, 'utf8')); } catch { return {}; } }
async function httpOk(url, timeoutMs = 3000) {
  try { const r = await fetch(url, { signal: AbortSignal.timeout(timeoutMs) }); return r.status < 500; } catch { return false; }
}
function alive(pid) { if (!Number.isInteger(pid) || pid <= 0) return false; try { process.kill(pid, 0); return true; } catch { return false; } }
async function waitFor(check, timeoutMs, stepMs = 1000) {
  const end = Date.now() + timeoutMs;
  while (Date.now() < end) { if (await check()) return true; await new Promise((r) => setTimeout(r, stepMs)); }
  return false;
}
async function spawnDetached(command, args, { cwd, env, logFile }) {
  await mkdir(dirname(logFile), { recursive: true });
  const fh = await open(logFile, 'a');
  const child = spawn(command, args, { cwd, env, detached: true, windowsHide: true, shell: false, stdio: ['ignore', fh.fd, fh.fd] });
  child.unref();
  await fh.close();
  return child.pid;
}
async function runToEnd(command, args, opts = {}) {
  return new Promise((res) => {
    const c = spawn(command, args, { stdio: 'inherit', windowsHide: true, shell: false, ...opts });
    c.on('error', () => res(127)); c.on('close', (code) => res(code ?? 1));
  });
}

export async function writeConfig(paths) {
  for (const d of [paths.base, paths.dataDir, paths.obsidianDir, paths.logsDir]) await mkdir(d, { recursive: true });
  const next = renderWorkerEnv(paths);
  const prev = existsSync(paths.workerEnvFile) ? await readFile(paths.workerEnvFile, 'utf8') : '';
  if (prev !== next) await writeFile(paths.workerEnvFile, next, 'utf8');
  // Persist the Hermes the Kernel must certify in the launcher config, so a Kernel started
  // later (login autostart, "Iniciar Efesto") certifies the same executable status reports.
  const launcherOpts = { env: kernelEnv(paths), cwd: paths.repoRoot };
  const current = await readLauncherConfig(launcherOpts);
  const launcherChanged = current.hermesExecutable !== paths.hermesExecutable || Number(current.port) !== KERNEL_PORT;
  if (launcherChanged) await writeLauncherConfig({ hermesExecutable: paths.hermesExecutable, port: KERNEL_PORT }, launcherOpts);
  return { changed: prev !== next || launcherChanged };
}

/** Ollama's per-user install dir, used when Explorer's PATH predates the install (shortcut launch). */
export function ollamaExecutable(env = process.env) {
  const local = env.LOCALAPPDATA ? join(env.LOCALAPPDATA, 'Programs', 'Ollama', 'ollama.exe') : '';
  return local && existsSync(local) ? local : 'ollama';
}

async function ensureOllama(paths, state) {
  const base = `http://${OLLAMA_HOST}`;
  if (!(await httpOk(`${base}/api/tags`))) {
    say('Arrancando Ollama...');
    state.ollama = await spawnDetached(ollamaExecutable(), ['serve'], { env: { ...process.env, OLLAMA_HOST, OLLAMA_CONTEXT_LENGTH: '8192' }, logFile: join(paths.logsDir, 'ollama.log') });
    if (!(await waitFor(() => httpOk(`${base}/api/tags`), 60_000))) throw new Error('Ollama no responde en 127.0.0.1:11434. ¿Está instalado? Vuelve a ejecutar "Instalar Efesto".');
  } else say('Ollama ya está en marcha.');
  const tags = await (await fetch(`${base}/api/tags`)).json().catch(() => ({}));
  if (!(tags.models ?? []).some((m) => m?.name === MODEL || m?.model === MODEL)) {
    say(`Descargando el modelo ${MODEL} (solo la primera vez, puede tardar varios minutos)...`);
    if ((await runToEnd(ollamaExecutable(), ['pull', MODEL])) !== 0) throw new Error(`No se pudo descargar el modelo ${MODEL}.`);
  } else say(`Modelo ${MODEL} disponible.`);
}

async function ensureKernel(paths) {
  if (await httpOk(`http://127.0.0.1:${KERNEL_PORT}/health`)) { say(`El Kernel ya responde en el puerto ${KERNEL_PORT}.`); return; }
  say(`Arrancando el Kernel en el puerto ${KERNEL_PORT}...`);
  // Reuse the existing launcher (pairing, owned-process record, Hermes certification) with our port and data dir.
  const code = await runToEnd(process.execPath, [join(paths.repoRoot, 'scripts', 'efesto-launcher.mjs'), 'repair'], { cwd: paths.repoRoot, env: kernelEnv(paths) });
  if (!(await waitFor(() => httpOk(`http://127.0.0.1:${KERNEL_PORT}/health`), 30_000))) throw new Error(`El Kernel no arrancó (código ${code}). Revisa ${paths.dataDir}\\logs.`);
}

async function ensureDashboard(paths, state) {
  if (await httpOk(`http://127.0.0.1:${DASHBOARD_PORT}/`)) { say('El panel ya está en marcha.'); return; }
  const dash = join(paths.repoRoot, 'apps', 'dashboard');
  if (!existsSync(join(dash, '.next', 'BUILD_ID'))) throw new Error('El panel no está compilado. Vuelve a ejecutar "Instalar Efesto".');
  say(`Arrancando el panel en http://127.0.0.1:${DASHBOARD_PORT} ...`);
  const bin = join(dash, 'node_modules', 'next', 'dist', 'bin', 'next');
  state.dashboard = await spawnDetached(process.execPath, [bin, 'start', '-H', '127.0.0.1', '-p', String(DASHBOARD_PORT)], { cwd: dash, env: dashboardEnv(paths), logFile: join(paths.logsDir, 'dashboard.log') });
  if (!(await waitFor(() => httpOk(`http://127.0.0.1:${DASHBOARD_PORT}/`), 90_000))) throw new Error(`El panel no respondió. Revisa ${join(paths.logsDir, 'dashboard.log')}.`);
}

async function ensureWorker(paths, state) {
  if (alive(state.worker)) { say('El trabajador de Hermes ya está en marcha.'); return; }
  if (!existsSync(paths.hermesExecutable)) throw new Error('Hermes no está instalado. Vuelve a ejecutar "Instalar Efesto".');
  say('Arrancando el trabajador de Hermes...');
  state.worker = await spawnDetached(process.execPath, [fileURLToPath(import.meta.url), 'supervise-worker'], { cwd: paths.repoRoot, env: process.env, logFile: join(paths.logsDir, 'hermes-worker.log') });
}

/** Restart loop like scripts/live-box/run-hermes-worker.sh, with the generated env file. */
async function superviseWorker(paths) {
  const env = { ...process.env, ...parseEnvFile(await readFile(paths.workerEnvFile, 'utf8')) };
  const script = join(paths.repoRoot, 'scripts', 'live-box', 'queue-worker.mjs');
  for (;;) {
    const code = await runToEnd(process.execPath, [script], { cwd: paths.repoRoot, env });
    console.log(`${new Date().toISOString()} queue worker exited (${code}); restarting in 15s`);
    await new Promise((r) => setTimeout(r, 15_000));
  }
}

async function killTree(pid) {
  if (!alive(pid)) return false;
  if (process.platform === 'win32') return (await runToEnd('taskkill.exe', ['/PID', String(pid), '/T', '/F'], { stdio: 'ignore' })) === 0;
  try { process.kill(pid, 'SIGTERM'); return true; } catch { return false; }
}

export async function start(paths) {
  const state = await readJson(paths.stateFile);
  const save = () => writeFile(paths.stateFile, `${JSON.stringify(state, null, 2)}\n`, 'utf8');
  const steps = stackPlan(paths);
  const run = { config: () => writeConfig(paths), ollama: () => ensureOllama(paths, state), kernel: () => ensureKernel(paths), dashboard: () => ensureDashboard(paths, state), worker: () => ensureWorker(paths, state) };
  for (const [i, s] of steps.entries()) {
    say(`Paso ${i + 1} de ${steps.length}: ${s.label}`);
    await run[s.id]();
    await save();
  }
  say(`Listo. Efesto está en ${DASHBOARD_URL}`);
}

/** Desktop/Start-menu "Efesto": start everything hidden, then open the dashboard in the default browser. */
export async function openEfesto(paths) {
  await start(paths);
  const { command, args } = browserOpenCommand();
  if (process.platform === 'win32') await runToEnd(command, args, { stdio: 'ignore' });
  else say(`Abre ${DASHBOARD_URL} en el navegador.`);
}

export async function stop(paths) {
  const state = await readJson(paths.stateFile);
  // Worker and dashboard were started by us; the Kernel belongs to the launcher, so ask it to shut down.
  for (const key of ['worker', 'dashboard']) {
    if (await killTree(state[key])) say(`Detenido: ${key === 'worker' ? 'trabajador de Hermes' : 'panel'}.`);
    delete state[key];
  }
  await runToEnd(process.execPath, [join(paths.repoRoot, 'scripts', 'efesto-launcher.mjs'), 'shutdown'], { cwd: paths.repoRoot, env: kernelEnv(paths), stdio: 'ignore' });
  say('Kernel detenido (si estaba en marcha). Ollama sigue disponible para otras aplicaciones.');
  await mkdir(paths.base, { recursive: true });
  await writeFile(paths.stateFile, `${JSON.stringify(state, null, 2)}\n`, 'utf8');
}

export async function status(paths) {
  const state = await readJson(paths.stateFile);
  return {
    ollama: await httpOk(`http://${OLLAMA_HOST}/api/tags`),
    kernel: await httpOk(`http://127.0.0.1:${KERNEL_PORT}/health`),
    dashboard: await httpOk(`http://127.0.0.1:${DASHBOARD_PORT}/`),
    worker: alive(state.worker),
    hermesInstalled: existsSync(paths.hermesExecutable),
  };
}

async function main(argv) {
  const command = argv[0] ?? 'start';
  const paths = windowsStackPaths();
  if (command === 'plan') { console.log(JSON.stringify({ paths, steps: stackPlan(paths), workerEnv: Object.fromEntries(workerEnvEntries(paths)) }, null, 2)); return; }
  if (command === 'write-config') { const r = await writeConfig(paths); say(r.changed ? 'Configuración escrita.' : 'Configuración ya al día.'); return; }
  if (command === 'start') return start(paths);
  if (command === 'open') return openEfesto(paths);
  if (command === 'stop') return stop(paths);
  if (command === 'status') {
    const s = await status(paths); const yes = (b) => (b ? 'sí' : 'no');
    say(`Ollama: ${yes(s.ollama)} · Kernel: ${yes(s.kernel)} · Panel: ${yes(s.dashboard)} · Trabajador: ${yes(s.worker)} · Hermes instalado: ${yes(s.hermesInstalled)}`);
    if (!(s.ollama && s.kernel && s.dashboard && s.worker)) process.exitCode = 1;
    return;
  }
  if (command === 'copy-token') {
    // Optional (browser-extension / manual pairing only; the installed dashboard does not need it).
    // Clipboard only (clip.exe via stdin); never printed.
    if (!existsSync(paths.tokenFile)) { say('Todavía no hay código de conexión (arranca Efesto primero).'); return; }
    const token = (await readFile(paths.tokenFile, 'utf8')).trim();
    const ok = await new Promise((res) => { const c = spawn('clip.exe', [], { stdio: ['pipe', 'ignore', 'ignore'], windowsHide: true }); c.on('error', () => res(false)); c.on('close', (code) => res(code === 0)); c.stdin.end(token); });
    say(ok ? 'Código de conexión copiado al portapapeles: en el panel pulsa «Conectar Kernel» y pega con Ctrl+V.' : `No se pudo copiar el código. Está guardado en ${paths.tokenFile}.`);
    return;
  }
  if (command === 'supervise-worker') return superviseWorker(paths);
  console.error(`Comando desconocido: ${command}`); process.exitCode = 2;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main(process.argv.slice(2)).catch((e) => { console.error(`[Efesto] Necesita atención: ${e.message}`); process.exitCode = 1; });
}
